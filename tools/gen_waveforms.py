"""Regenerate app/waveforms.c from Feeder's coyote-sequences.js.

Usage: python3 tools/gen_waveforms.py [path/to/coyote-sequences.js] [--with-dglab]
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.expanduser("~/feeder-2.0/server/lib/coyote-sequences.js")

# Display names (<=12 chars so they fit one line); order matches the JS file.
#
# CORE_NAMES are Feeder's own waveforms and ship in this repo. DGLAB_NAMES are
# the official DG-Lab app's presets: DG-Lab grant no licence and ask that their
# content not be used commercially, which cannot be reconciled with this app's
# GPL-3.0 (see README "Licensing"). They are therefore NOT committed, and are
# only included when you pass --with-dglab for a local build.
CORE_NAMES = {
    "HEARTBEAT": "Heartbeat", "BREATH": "Breath", "KNOCK": "Knock", "WAVE": "Wave",
    "STUTTER": "Stutter", "RAMP_UP_DROP": "Ramp & drop", "THRUM": "Thrum",
    "BURST_TRAIN": "Burst train", "SLOW_BURN": "Slow burn", "CHAOS": "Chaos",
    "CUSTOM_A": "Tap squeeze", "CUSTOM_B": "Light taps", "CUSTOM_C": "3 light taps",
    "CUSTOM_D": "Low buzz", "CUSTOM_E": "Squeeze", "CUSTOM_F": "Fast taps",
    "CUSTOM_G": "Tap to buzz", "CUSTOM_H": "Tap to buzz 2", "CUSTOM_I": "Hit / pulse",
    "CUSTOM_J": "Slow pulse", "CUSTOM_K": "Ramp 2",
}

# Official DG-Lab app 4.2.6 presets, in the app's order.
DGLAB_NAMES = {
    "EXTRUSION_DG": "Extrusion DG",
    "BUBBLE_DG": "Bubble DG",
    "RHYTHM_DG": "Rhythm DG",
    "AIR_WAVES_DG": "Air waves DG",
    "DANCE_DG": "Dance DG",
    "CLIMB_DG": "Climb DG",
    "SHADE_DG": "Shade DG",
    "PULSE_DG": "Pulse DG",
    "BREATHING_DG": "Breathing DG",
    "TIDE_DG": "Tide DG",
    "PULSATING_DG": "Pulsating DG",
    "QUICK_RUB_DG": "Quick rub DG",
    "GRADUAL_RUB_DG": "Grad. rub DG",
    "HEARTBEAT_DG": "Heartbeat DG",
    "COMPRESS_DG": "Compress DG",
    "RHYTHMIC_DG": "Rhythmic DG",
    "GRAINY_DG": "Grainy DG",
    "BOUNCY_DG": "Bouncy DG",
    "RIPPLE_DG": "Ripple DG",
    "RAINFALL_DG": "Rainfall DG",
    "TEMPO_TAP_DG": "Tempo tap DG",
    "SIGNAL_DG": "Signal DG",
    "TEASE_1_DG": "Tease 1 DG",
    "TEASE_2_DG": "Tease 2 DG",
}

WITH_DGLAB = "--with-dglab" in sys.argv
ARGS = [a for a in sys.argv[1:] if not a.startswith("--")]
SRC = ARGS[0] if ARGS else SRC
NAMES = dict(CORE_NAMES)
if WITH_DGLAB:
    NAMES.update(DGLAB_NAMES)

src = re.sub(r"//.*", "", open(SRC).read())
seqs = []
for m in re.finditer(r"(\w+)\s*:\s*\[((?:\s*\[[^\]]*\]\s*,?)+)\s*\]", src):
    frames = [tuple(int(v) for v in f.split(",")) for f in re.findall(r"\[([^\]]*)\]", m.group(2))]
    seqs.append((m.group(1), frames))
known = [(name, frames) for name, frames in seqs if name in NAMES]
missing = [name for name in NAMES if name not in dict(known)]
if missing:
    sys.exit(f"{SRC} is missing: {missing}")
if [name for name, _ in known] != list(NAMES):
    sys.exit(f"sequence order differs from NAMES: {[name for name, _ in known]}")
seqs = known
for name, frames in seqs:
    for x, y, z in frames:
        if not (0 <= x <= 31 and 0 <= y <= 1023 and 0 <= z <= 31):
            sys.exit(f"{name}: frame out of range: {x}, {y}, {z}")

out = ["// SPDX-License-Identifier: GPL-3.0-or-later",
       "// Copyright (C) 2026 KinkyTechieKitty",
       "// Generated from feeder-2.0/server/lib/coyote-sequences.js by tools/gen_waveforms.py.",
       "// Do not edit by hand.", '#include "waveforms.h"', "",
       "#ifndef COUNT_OF", "#define COUNT_OF(x) (sizeof(x) / sizeof((x)[0]))", "#endif", ""]
for name, frames in seqs:
    out.append(f"static const CoyoteFrame wf_{name.lower()}[] = {{")
    out += [f"    {{{x}, {y}, {z}}}," for x, y, z in frames]
    out.append("};")
out.append("\nconst CoyoteWaveform coyote_waveforms[COYOTE_WAVEFORM_COUNT] = {")
for name, _ in seqs:
    out.append(f'    {{"{NAMES[name]}", wf_{name.lower()}, COUNT_OF(wf_{name.lower()})}},')
out.append("};\n")
open(os.path.join(HERE, "..", "app", "waveforms.c"), "w").write("\n".join(out))

# The count lives beside the table: the committed build has 21 waveforms and a
# --with-dglab build has 45, and waveforms.h derives its masks from this.
header = [
    "// SPDX-License-Identifier: GPL-3.0-or-later",
    "// Copyright (C) 2026 KinkyTechieKitty",
    "// Generated by tools/gen_waveforms.py. Do not edit by hand.",
    "#pragma once",
    "",
    f"#define COYOTE_WAVEFORM_COUNT {len(seqs)}",
    "",
]
# A DG-Lab build keeps its own settings file: its waveform masks set bits the
# 21-waveform build rejects in coyote_settings_validate(), so sharing one file
# would silently reset whichever build opened it second.
if WITH_DGLAB:
    header += ["#define COYOTE_WITH_DGLAB 1", ""]
open(os.path.join(HERE, "..", "app", "waveforms_generated.h"), "w").write("\n".join(header))
print(f"{len(seqs)} waveforms written ({'with' if WITH_DGLAB else 'without'} DG-Lab presets)")
